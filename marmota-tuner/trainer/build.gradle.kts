import groovy.json.JsonSlurper

// Marmota Trainer: the website's ear and voice training (/treino-de-ouvido, /treino-de-voz) as an Android app.
// The logic is :core (package treino), the same Kotlin the website runs compiled to JS. Screens are Android Views built in code,
// like :app (no AndroidX). The piano samples and the interface texts come from the website at build time, so nothing is copied.
plugins {
    id("com.android.application")
}

android {
    namespace = "br.musica.marmotaear"
    compileSdk = 35

    defaultConfig {
        applicationId = "br.musica.marmotaear"
        minSdk = 26
        targetSdk = 35
        versionCode = 10
        versionName = "1.7"
    }

    // Same release key as the tuner (~/.gradle/gradle.properties); without it, release builds come out unsigned.
    val releaseKeystore = providers.gradleProperty("MARMOTA_KEYSTORE").orNull
    signingConfigs {
        if (releaseKeystore != null) {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = providers.gradleProperty("MARMOTA_KEYSTORE_PASSWORD").get()
                keyAlias = providers.gradleProperty("MARMOTA_KEY_ALIAS").get()
                keyPassword = providers.gradleProperty("MARMOTA_KEYSTORE_PASSWORD").get()
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"))
            if (releaseKeystore != null) signingConfig = signingConfigs.getByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
}

dependencies {
    implementation(project(":core"))
    implementation(project(":android-common"))
    testImplementation("junit:junit:4.13.2")
}

val site = rootDir.resolve("..")

/** The 14 piano samples (the mp3 files in public/sons/piano) as assets/piano. */
abstract class CopyPiano : DefaultTask() {
    @get:InputDirectory abstract val from: DirectoryProperty
    @get:OutputDirectory abstract val out: DirectoryProperty

    @TaskAction fun run() {
        val dest = out.get().asFile.resolve("piano")
        dest.deleteRecursively()
        dest.mkdirs()
        from.get().asFile.listFiles { f -> f.extension == "mp3" || f.name == "LICENCA.txt" }!!.forEach { it.copyTo(dest.resolve(it.name)) }
    }
}

/**
 * The interface texts of the "treino-de-ouvido" namespace of messages/pt-BR.json, the same the website shows, as a Kotlin map
 * (Textos.kt). Keys are flattened with dots ("voz.exercicios.igualar"); Fmt.kt formats the ICU placeholders and plurals.
 */
abstract class GenerateTextos : DefaultTask() {
    @get:InputFile abstract val messages: RegularFileProperty
    @get:OutputDirectory abstract val out: DirectoryProperty

    @TaskAction fun run() {
        @Suppress("UNCHECKED_CAST")
        val ns = (JsonSlurper().parse(messages.get().asFile) as Map<String, Any?>)["treino-de-ouvido"] as Map<String, Any?>
        val flat = linkedMapOf<String, String>()
        fun walk(m: Map<*, *>, prefix: String) {
            for ((k, v) in m) {
                val key = if (prefix.isEmpty()) k.toString() else "$prefix.$k"
                if (v is Map<*, *>) walk(v, key) else flat[key] = v.toString()
            }
        }
        walk(ns, "")
        fun str(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$").replace("\n", "\\n") + "\""
        val f = out.get().asFile.resolve("br/musica/marmotaear/Textos.kt")
        f.parentFile.mkdirs()
        f.writeText(buildString {
            append("// GENERATED by :trainer from messages/pt-BR.json (namespace treino-de-ouvido). Do not edit.\n")
            append("package br.musica.marmotaear\n\ninternal val TEXTOS: Map<String, String> = hashMapOf(\n")
            for ((k, v) in flat) append("    ${str(k)} to ${str(v)},\n")
            append(")\n")
        })
    }
}

val copyPiano = tasks.register<CopyPiano>("copyPiano") {
    from.set(site.resolve("public/sons/piano"))
    out.set(layout.buildDirectory.dir("generated/piano"))
}
val generateTextos = tasks.register<GenerateTextos>("generateTextos") {
    messages.set(site.resolve("messages/pt-BR.json"))
    out.set(layout.buildDirectory.dir("generated/textos"))
}

androidComponents {
    onVariants { v ->
        v.sources.assets?.addGeneratedSourceDirectory(copyPiano, CopyPiano::out)
        v.sources.java?.addGeneratedSourceDirectory(generateTextos, GenerateTextos::out)
    }
}
