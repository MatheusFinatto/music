/** Frase de ouvido. `section` é a seção cuja matéria a frase usa; `base` é a base por baixo (padrão: Am F). */
const ear = (id: string, section: "s1" | "s2" | "s3" | "s4", p: Phrase, base: Base = AM_F): EchoExercise => ({
  id,
  kind: "echo",
  section,
  title: `Frase: ${p.name}`,
  goal: "Tire esta frase de ouvido, sem ver onde ela fica no braço.",
  steps: [
    "Ouça duas ou três vezes sem tocar.",
    "Cante junto. Se não consegue cantar, ainda não ouviu direito.",
    WHERE[section]!,
    "Só então abra o braço para conferir.",
  ],
  check: "Tocou a frase inteira antes de conferir no braço?",
  base,
  reveal: "tab",
  phrases: [p],
});

